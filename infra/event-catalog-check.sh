#!/usr/bin/env bash
# infra/event-catalog-check.sh — the paywall event catalog is the single source of truth (GOAL D9, AC-1).
#
# Events are named ONLY in cmp-paycraft-core/.../analytics/PayCraftEvent.kt (enum PayCraftEventName). SDK
# code emits the typed enum, so an off-catalog name cannot compile; what CAN slip through is a raw string
# handed to an emit/forward call, and the server's copy of the catalog drifting from the enum. This gate
# checks exactly those two. (The `paycraft_` prefix is also used by test tags and storage keys — those are
# not events and are not checked.)
#
#   bash infra/event-catalog-check.sh [--root DIR]     # exit 1 on a raw event string or a stale server catalog
#   bash infra/event-catalog-check.sh --emit-ts        # (re)write the server catalog from the enum, then check
set -euo pipefail
ROOT="."; EMIT=0
while [[ $# -gt 0 ]]; do case "$1" in
  --root) ROOT="$2"; shift 2;; --emit-ts) EMIT=1; shift;;
  *) echo "usage: $0 [--root DIR] [--emit-ts]"; exit 2;; esac; done
CAT="$ROOT/cmp-paycraft-core/src/commonMain/kotlin/com/mobilebytelabs/paycraft/analytics/PayCraftEvent.kt"
TS="$ROOT/supabase/functions/_shared/event-catalog.ts"
[[ -f "$CAT" ]] || { echo "FAIL catalog not found: $CAT"; exit 2; }
catalog="$(grep -oE '"paycraft_[a-z_]+"' "$CAT" | tr -d '"' | sort -u)"
[[ -n "$catalog" ]] || { echo "FAIL catalog declares no paycraft_* names"; exit 2; }
fail=0

# 1. No raw event-name string at an emit / forward call site — events go through PayCraftEventName.
raw="$(for d in cmp-paycraft/src cmp-paycraft-core/src cmp-paycraft-web/src cmp-paycraft-web-survey/src; do
  [[ -d "$ROOT/$d" ]] && grep -rnE '(emit|track|logEvent|onEvent|sendEvent)\([^)]*"paycraft_[a-z_]+"' --include='*.kt' "$ROOT/$d" || true
done)"
if [[ -n "$raw" ]]; then echo "FAIL raw event-name string at an emit call — use PayCraftEventName:"; echo "$raw"; fail=1; fi

# 2. The server's ingest catalog (supabase/functions/_shared/event-catalog.ts) is generated from the enum.
render_ts() {
  echo "// GENERATED by infra/event-catalog-check.sh --emit-ts from PayCraftEvent.kt — do not edit."
  echo "export const EVENT_CATALOG: ReadonlySet<string> = new Set(["
  sed 's/^/  "/; s/$/",/' <<<"$catalog"
  echo "])"
}
if [[ $EMIT == 1 ]]; then mkdir -p "$(dirname "$TS")"; render_ts > "$TS"; fi
if [[ -f "$TS" ]] && ! diff -q <(render_ts) "$TS" > /dev/null; then
  echo "FAIL $TS is stale — run: bash infra/event-catalog-check.sh --emit-ts"; fail=1
fi

[[ $fail == 0 ]] && echo "PASS event catalog ($(wc -l <<<"$catalog" | tr -d ' ') names)"
exit $fail
